// Generates supabase/migrations/002_canon.sql from the game content.
// Run after changing any case content: npm run gen:canon
import { writeFileSync } from 'node:fs';
import { allCanon } from '../src/events/canon.js';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;

let sql = `-- GENERATED by scripts/gen-canon-sql.mjs from src/content — do not edit by hand.\n`;
sql += `-- Canonical rewards, puzzle answers and final-deduction rules used for server-side validation.\n\n`;
sql += `delete from noct.canon_rewards;\ndelete from noct.canon_puzzles;\ndelete from noct.canon_final;\n\n`;
for (const c of allCanon()) {
  for (const r of c.rewards) {
    sql += `insert into noct.canon_rewards (case_id, reward_id, score, hint, requires) values (${q(c.case_id)}, ${q(r.reward_id)}, ${r.score}, ${r.hint}, ${j(r.requires)});\n`;
  }
  for (const p of c.puzzles) {
    sql += `insert into noct.canon_puzzles (case_id, puzzle_id, type, answer, filler, requires) values (${q(c.case_id)}, ${q(p.puzzle_id)}, ${q(p.type)}, ${j(p.answer)}, ${arr(p.filler)}, ${j(p.requires)});\n`;
    sql += `insert into noct.canon_rewards (case_id, reward_id, score, hint, requires) values (${q(c.case_id)}, ${q('puzzle:' + p.puzzle_id)}, ${p.score}, ${p.hint}, ${j(p.requires)});\n`;
  }
  const f = c.final;
  sql += `insert into noct.canon_final (case_id, requires, questions, essential, rumor_clues, completion) values (${q(c.case_id)}, ${j(f.requires)}, ${j(f.questions)}, ${arr(f.essential)}, ${arr(f.rumor_clues)}, ${j(f.completion)});\n\n`;
}
writeFileSync(new URL('../supabase/migrations/002_canon.sql', import.meta.url), sql);
console.log('wrote supabase/migrations/002_canon.sql');
